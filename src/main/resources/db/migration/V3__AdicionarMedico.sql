ID_MEDICO BIGINT PRIMARY KEY AUTO_INCREMENT NOT NULL,

cirurgiao Boolean,
nome VARCHAR(50) NOT NULL,
crm VARCHAR(20) UNIQUE NOT NULL,
especializacao ENUM('PEDIATRA','OFTOMOLOGISTA','NÃO RELATADO') DEFAULT 'NÃO RELATADO' NULL,


ID_USUARIO_MEDICO BIGINT,

CONSTRAINT  fk_Usuario_Medico FOREIGN KEY (ID_USUARIO_MEDICO) REFERENCES USUARIO_MEDICO(ID_USUARIO_MEDICO)


);